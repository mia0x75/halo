-- 群集分组表。
--
-- 用户的组用角色（mm_roles）表达，群集服务器的组用本表表达：群集通过
-- mm_clusters.group_id 归属分组，角色通过 mm_edges 关联分组，实现组间权限隔离。

CREATE TABLE IF NOT EXISTS mm_groups (
    group_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid        CHAR(36) NOT NULL,
    name        VARCHAR(75) NOT NULL,
    description VARCHAR(150) NOT NULL DEFAULT '',
    status      SMALLINT NOT NULL DEFAULT 1,
    version     BIGINT NOT NULL DEFAULT 0,
    update_at   TIMESTAMPTZ NULL DEFAULT NULL,
    create_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_mm_groups_uuid UNIQUE (uuid),
    CONSTRAINT uq_mm_groups_name UNIQUE (name)
);
COMMENT ON TABLE mm_groups IS '群集分组表';

-- 群集归属分组，0 表示未分组。
ALTER TABLE mm_clusters
    ADD COLUMN IF NOT EXISTS group_id BIGINT NOT NULL DEFAULT 0;
