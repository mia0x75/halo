-- 规则命中明细表。
--
-- 命中结果原先只以文本形式写进 mm_statements.report，无法按级别或规则聚合，
-- Dashboard 的「命中分级」「命中 Top 规则」没有数据来源。本表按工单、语句、
-- 规则保留每一条命中明细，聚合类统计由 mm_metrics 承担。

CREATE TABLE IF NOT EXISTS mm_violations (
    violation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid         CHAR(36) NOT NULL,
    ticket_id    BIGINT NOT NULL,
    sequence     INTEGER NOT NULL DEFAULT 0,
    rule_name    VARCHAR(75) NOT NULL,
    level        SMALLINT NOT NULL,
    message      VARCHAR(150) NOT NULL,
    create_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_mm_violations_uuid UNIQUE (uuid)
);
COMMENT ON TABLE mm_violations IS '规则命中明细表';
CREATE INDEX IF NOT EXISTS idx_mm_violations_ticket ON mm_violations (ticket_id);
CREATE INDEX IF NOT EXISTS idx_mm_violations_rule ON mm_violations (rule_name);
CREATE INDEX IF NOT EXISTS idx_mm_violations_level ON mm_violations (level, create_at);
