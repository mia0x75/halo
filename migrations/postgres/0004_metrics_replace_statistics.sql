-- 指标表取代统计表。
--
-- 旧表用「分组 + 键」表达指标，counter 与 gauge 混在一张表里：所有写入都走
-- value = value + delta，导致 latest-login 这类 gauge 指标被累加。新表把维度
-- 拆成「名称 + 作用域 + 作用域实体 + 时间桶」，并显式区分 counter 与 gauge。
--
-- 本脚本可重复执行：目标库若已按权威 schema 建好（mm_metrics 存在、
-- mm_statistics 已删除），数据搬迁会跳过，只补台账。

CREATE TABLE IF NOT EXISTS mm_metrics (
    metric_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid      CHAR(36) NOT NULL,
    name      VARCHAR(75) NOT NULL,
    scope     SMALLINT NOT NULL DEFAULT 0,
    scope_id  CHAR(36) NOT NULL DEFAULT '',
    type      SMALLINT NOT NULL DEFAULT 0,
    bucket    VARCHAR(20) NOT NULL DEFAULT '',
    value     NUMERIC(18,4) NOT NULL DEFAULT 0,
    version   BIGINT NOT NULL DEFAULT 0,
    update_at TIMESTAMPTZ NULL DEFAULT NULL,
    create_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_mm_metrics_uuid UNIQUE (uuid),
    CONSTRAINT uq_mm_metrics_key UNIQUE (name, scope, scope_id, bucket)
);
COMMENT ON TABLE mm_metrics IS '指标表';

-- 旧数据搬迁：分组决定作用域与指标名，键在按天分组里是时间桶。
DO $halo$
BEGIN
    IF EXISTS(SELECT 1 FROM information_schema.tables
              WHERE table_schema = current_schema() AND table_name = 'mm_statistics') THEN
        INSERT INTO mm_metrics (uuid, name, scope, scope_id, type, bucket, value, version, update_at, create_at)
        SELECT uuid,
               CASE WHEN "group" = 'tickets-daily' THEN 'total-tickets'
                    WHEN "group" = 'queries-daily' THEN 'total-queries'
                    ELSE "key" END,
               CASE WHEN "group" IN ('tickets-daily', 'queries-daily') THEN 1
                    WHEN "group" ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$' THEN 2
                    ELSE 0 END,
               CASE WHEN "group" ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$' THEN "group"
                    ELSE '' END,
               CASE WHEN "key" = 'latest-login' THEN 1 ELSE 0 END,
               CASE WHEN "group" IN ('tickets-daily', 'queries-daily') THEN "key"
                    ELSE '' END,
               value, version, update_at, create_at
        FROM mm_statistics
        ON CONFLICT (name, scope, scope_id, bucket) DO NOTHING;
    END IF;
END
$halo$;

DROP TABLE IF EXISTS mm_statistics;
