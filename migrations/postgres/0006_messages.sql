-- 站内消息表。
--
-- mm_logs 是全局操作日志，没有收件箱语义与已读状态，顶栏的未读数没有数据来源。
-- 本表按接收人存放站内消息，支持未读计数与标记已读。

CREATE TABLE IF NOT EXISTS mm_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid       CHAR(36) NOT NULL,
    user_id    BIGINT NOT NULL,
    category   VARCHAR(30) NOT NULL DEFAULT '',
    title      VARCHAR(75) NOT NULL,
    content    TEXT NOT NULL,
    link       VARCHAR(150) NOT NULL DEFAULT '',
    read_at    TIMESTAMPTZ NULL DEFAULT NULL,
    create_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_mm_messages_uuid UNIQUE (uuid)
);
COMMENT ON TABLE mm_messages IS '站内消息表';
CREATE INDEX IF NOT EXISTS idx_mm_messages_user_read ON mm_messages (user_id, read_at);
CREATE INDEX IF NOT EXISTS idx_mm_messages_user_create ON mm_messages (user_id, create_at);
