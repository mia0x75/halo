-- 异步任务执行表。
--
-- 定时任务（mm_crons）存的是调度定义，internal/worker 的任务实例只存在内存里，
-- 重启即丢，也无法追查执行历史。本表记录每一次执行：状态、重试次数、起止时间
-- 与失败原因，是「执行必经审计」的落点。

CREATE TABLE IF NOT EXISTS mm_tasks (
    task_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid         CHAR(36) NOT NULL,
    name         VARCHAR(75) NOT NULL,
    type         VARCHAR(30) NOT NULL DEFAULT '',
    payload      TEXT NOT NULL,
    status       SMALLINT NOT NULL DEFAULT 0,
    priority     SMALLINT NOT NULL DEFAULT 0,
    attempt      SMALLINT NOT NULL DEFAULT 0,
    max_attempt  SMALLINT NOT NULL DEFAULT 3,
    cron_id      BIGINT NOT NULL DEFAULT 0,
    scheduled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at   TIMESTAMPTZ NULL DEFAULT NULL,
    finished_at  TIMESTAMPTZ NULL DEFAULT NULL,
    error        TEXT NOT NULL,
    version      BIGINT NOT NULL DEFAULT 0,
    update_at    TIMESTAMPTZ NULL DEFAULT NULL,
    create_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_mm_tasks_uuid UNIQUE (uuid)
);
COMMENT ON TABLE mm_tasks IS '异步任务执行表';
CREATE INDEX IF NOT EXISTS idx_mm_tasks_status_scheduled ON mm_tasks (status, scheduled_at);
CREATE INDEX IF NOT EXISTS idx_mm_tasks_type ON mm_tasks (type);

-- 定时任务补齐审计维度：谁配置的、跑在哪个群集。
ALTER TABLE mm_crons
    ADD COLUMN IF NOT EXISTS user_id BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS cluster_id BIGINT NOT NULL DEFAULT 0;
